import buildingData from './data/buildings.json' with { type: 'json' };
import { ELEMENT_COSTS, RESOURCES, STORAGE, storageCapacity } from './tech.js';
import type { PlanetType } from './types.js';

/**
 * The game's buildings page as numbers (`ShowBuildingsPage`, `BuildFunctions`): which buildings a planet or moon can
 * build, the cost and build time of the next level, and when the resources for it are there, from the production per
 * hour and the resources of fleets landing on it. Used by the web app and by the server's notifications alike.
 */

/** building id -> planet types it can be built on, max level, requirements (element id -> level); generated by gen-costs */
export const BUILDINGS: Record<string, { on: PlanetType[]; max: number; req: Record<string, number> }> = buildingData as never;

/** Filter groups of the game's buildings page: mines and power plants, storages, the rest. */
export const PRODUCTION_BUILDINGS = [1, 2, 3, 4, 12];
export const STORAGE_BUILDINGS = [22, 23, 24];
export type BuildingGroup = 'prod' | 'storage' | 'other';
export const buildingGroup = (id: number): BuildingGroup =>
  PRODUCTION_BUILDINGS.includes(id) ? 'prod' : STORAGE_BUILDINGS.includes(id) ? 'storage' : 'other';

export const ROBOT_FACTORY = 14;
export const NANITE_FACTORY = 15;

/**
 * Buildings the game does not build while a facility is in use ("Busy" on the buildings page): TechnoDome and research
 * lab while research runs (on any planet), nanite factory and shipyard while the planet's shipyard works.
 */
export const LOCKED_BY: Record<number, 'research' | 'shipyard'> = { 6: 'research', 31: 'research', 15: 'shipyard', 21: 'shipyard' };

/**
 * Level a queue entry leaves the building at: the game queues a build with the level it reaches, a demolition with
 * the level it takes down ("Metallmine 25 Abreißen" leaves 24).
 */
export const levelAfter = (q: { level: number; destroy: boolean }) => (q.destroy ? q.level - 1 : q.level);

/** Robot and nanite factory levels once the queue is done (a build added now uses them, like `getBuildingTime`). */
export function factoriesAfterQueue(p: Pick<BuildPlanet, 'values' | 'queue'>): { robot: number; nanite: number } {
  let robot = p.values[ROBOT_FACTORY] ?? 0;
  let nanite = p.values[NANITE_FACTORY] ?? 0;
  for (const q of p.queue) {
    if (q.id === ROBOT_FACTORY) robot = levelAfter(q);
    if (q.id === NANITE_FACTORY) nanite = levelAfter(q);
  }
  return { robot, nanite };
}

/** Buildings of a planet type in the game's order (element id). */
export const buildingsFor = (type: PlanetType): number[] =>
  Object.entries(BUILDINGS)
    .filter(([, b]) => b.on.includes(type))
    .map(([id]) => Number(id));

/**
 * Cost of a building level (`getElementPrice`): base × factor^(level-1), metal/crystal/deuterium reduced by the
 * catch-up bonus (percent).
 */
export function buildingCost(id: number, level: number, catchUp = 0): Record<number, number> {
  const c = ELEMENT_COSTS[String(id)];
  if (!c) return {};
  const scale = (c[3] !== 1 && c[3] !== 0 ? Math.pow(c[3], level - 1) : 1) * (1 - catchUp / 100);
  const cost: Record<number, number> = {};
  RESOURCES.forEach((r, i) => {
    if (c[i]) cost[r] = c[i] * scale;
  });
  return cost;
}

/**
 * Catch-up bonus in percent like the game's `PlayerUtil::getCatchUpFactor`: from the own points (buildings ×1 +
 * research ×0.8 + fleet ×0.6, latest statistics) against the best player's, 10 × 0.9747^(% of the leader), at least 1,
 * mapped linearly onto 0 … `maxBonus` percent (the game: factor 0.5 at most, i.e. 50 %). It lowers the costs of
 * buildings and research and with them the build time.
 */
export function catchUpBonus(ownWeighted: number, leaderWeighted: number, maxBonus = 50): number {
  const raw = Math.max(1, 10 * Math.pow(0.9747, (Math.max(ownWeighted, 1) / Math.max(leaderWeighted, 1)) * 100));
  return (maxBonus / 9) * (raw - 1);
}

/**
 * The exact catch-up bonus (percent) behind the costs a buildings page shows: the page only prints it rounded to two
 * decimals, the costs are rounded to whole units. Each cost narrows the factor to [(x − ½) / base, (x + ½) / base];
 * the middle of what all costs allow. Null without costs or when they don't fit one factor.
 */
export function catchUpFromCosts(page: {
  buildings: { id: number; level: number; cost: Record<number, number> }[];
  queue: { id: number; level: number; destroy: boolean }[];
}): number | null {
  let lo = 0;
  let hi = Infinity;
  for (const b of page.buildings) {
    const queued = [...page.queue].reverse().find((q) => q.id === b.id);
    const base = buildingCost(b.id, (queued ? levelAfter(queued) : b.level) + 1);
    for (const r of RESOURCES) {
      const x = b.cost[r];
      if (!x || !base[r]) continue;
      lo = Math.max(lo, (x - 0.5) / base[r]);
      hi = Math.min(hi, (x + 0.5) / base[r]);
    }
  }
  if (!Number.isFinite(hi) || lo > hi) return null;
  return (1 - (lo + hi) / 2) * 100;
}

/** Build time in seconds (`getBuildingTime`): (metal + crystal) / (speed × (1 + robot factory)) × 0.5^nanite factory hours. */
export function buildTime(cost: Record<number, number>, robot: number, nanite: number, speed: number): number {
  const sum = (cost[901] ?? 0) + (cost[902] ?? 0);
  return Math.max(1, Math.floor((sum / (speed * (1 + robot))) * Math.pow(0.5, nanite) * 3600));
}

/**
 * Building speed of the universe (game config `building_speed`) from a build time the game showed; null when the time
 * is too short to tell (it is rounded down to seconds).
 */
export function deriveBuildingSpeed(cost: Record<number, number>, time: number, robot: number, nanite: number): number | null {
  const sum = (cost[901] ?? 0) + (cost[902] ?? 0);
  if (time < 600 || sum <= 0) return null;
  return Math.round((sum * 3600 * Math.pow(0.5, nanite)) / ((1 + robot) * time));
}

export interface Requirement {
  id: number;
  need: number;
  own: number;
}

/** Requirements of a building with the own levels (buildings of the planet, research of the account). */
export function requirementsOf(id: number, levels: Record<string, number>, research: Record<string, number>): Requirement[] {
  return Object.entries(BUILDINGS[String(id)]?.req ?? {}).map(([req, need]) => ({
    id: Number(req),
    need,
    own: Number(req) >= 100 ? (research[req] ?? 0) : (levels[req] ?? 0),
  }));
}

/** Resources of a fleet that land on a planet/moon at `at` (epoch seconds). */
export interface Arrival {
  at: number;
  resources: Record<number, number>;
  /** game mission id of the flight (3 transport, 4 deploy, 8 recycle …) */
  mission: number | null;
  /** return flight */
  back: boolean;
}

/**
 * Amount of a resource at `t` (epoch seconds): production per hour since `from`, which stops at the storage capacity
 * (consumption also empties full storages), plus the fleets landing until then (they may fill above the capacity).
 */
export function resourceAt(start: number, perHour: number, cap: number, from: number, t: number, arrivals: { at: number; amount: number }[] = []): number {
  let value = start;
  let at = from;
  const grow = (until: number) => {
    const dt = Math.max(0, until - at);
    if (perHour < 0) value = Math.max(0, value + (perHour * dt) / 3600);
    else if (value < cap) value = Math.min(cap, value + (perHour * dt) / 3600);
    at = Math.max(at, until);
  };
  for (const a of [...arrivals].sort((x, y) => x.at - y.at)) {
    if (a.at <= from) continue;
    if (a.at > t) break;
    grow(a.at);
    value += a.amount;
  }
  grow(t);
  return value;
}

/**
 * When a resource reaches `need` (epoch seconds): `from` when already there, null when production and the arriving
 * fleets never get there (no production, or more than the storage holds).
 */
export function resourceReadyAt(need: number, start: number, perHour: number, cap: number, from: number, arrivals: { at: number; amount: number }[] = []): number | null {
  if (start >= need) return from;
  let value = start;
  let at = from;
  /** time production reaches `need` before `until`, else grows the value to `until` */
  const grow = (until: number): number | null => {
    if (perHour > 0 && value < cap && need <= cap) {
      const reach = at + ((need - value) / perHour) * 3600;
      if (reach <= until) return Math.ceil(reach);
    }
    const dt = Math.max(0, until - at);
    if (perHour < 0) value = Math.max(0, value + (perHour * dt) / 3600);
    else if (value < cap) value = Math.min(cap, value + (perHour * dt) / 3600);
    at = until;
    return null;
  };
  for (const a of [...arrivals].sort((x, y) => x.at - y.at)) {
    if (a.at <= from) continue;
    const t = grow(a.at);
    if (t != null) return t;
    value += a.amount;
    if (value >= need) return a.at;
  }
  return grow(Infinity);
}

/** A planet or moon as the calculation needs it. */
export interface BuildPlanet {
  type: PlanetType;
  /** building levels */
  values: Record<string, number>;
  /** 901-903 at `time` */
  resources: Record<string, number>;
  perHour: Record<string, number>;
  /** storage capacity per resource when known (resource bar), else from the storage levels */
  storage?: Record<string, number>;
  /** epoch seconds of `resources` */
  time: number;
  fields?: { used: number; max: number };
  /** build queue (target levels), first in progress; `end` epoch seconds when known */
  queue: { id: number; level: number; destroy: boolean; end?: number | null }[];
  /** facilities in use: research (account wide) and the planet's shipyard; `until` epoch seconds, null when unknown */
  busy?: { research?: { until: number | null } | null; shipyard?: { until: number | null } | null };
}

export type BuildState = 'buildable' | 'busy' | 'resources' | 'requirements' | 'max' | 'fields' | 'storage' | 'never';

export interface BuildingInfo {
  id: number;
  group: BuildingGroup;
  level: number;
  /** level the next build reaches (after the queue) */
  next: number;
  max: number;
  requirements: Requirement[];
  cost: Record<number, number>;
  /** missing resources at `now` (fleets landed until then count), not rounded */
  missing: Record<number, number>;
  /** when the resources are there (epoch seconds, in the past when they already are), null when never */
  readyAt: number | null;
  /** build time in seconds with the robot and nanite factories after the queue, null without a known building speed */
  time: number | null;
  /** the facility the building waits for (`LOCKED_BY`) and until when, null when free */
  busy: { by: 'research' | 'shipyard'; until: number | null } | null;
  state: BuildState;
}

export interface BuildOptions {
  research: Record<string, number>;
  /** catch-up bonus in percent */
  catchUp?: number | null;
  /** universe building speed, null when unknown */
  buildingSpeed?: number | null;
  /** storage factor of the universe (when the planet has no `storage`) */
  storageFactor?: number;
  arrivals?: Arrival[];
  now: number;
  /** cost and build time of a level as the game's buildings page showed them; used when it is still the next level */
  shown?: Record<string, { next: number; cost: Record<number, number>; time: number | null }>;
}

/** Storage capacity of a resource of the planet. */
export function capacityOf(p: BuildPlanet, res: number, factor = 1): number {
  return p.storage?.[res] ?? storageCapacity(p.values[STORAGE[res]] ?? 0, factor);
}

/** Every building of the planet type with its next level, like the game's buildings page. */
export function buildingsOf(p: BuildPlanet, o: BuildOptions): BuildingInfo[] {
  const queuedFields = p.queue.reduce((n, q) => n + (q.destroy ? -1 : 1), 0);
  const fieldsFull = !!p.fields && p.fields.max > 0 && p.fields.used + queuedFields >= p.fields.max;
  const { robot, nanite } = factoriesAfterQueue(p);
  const factoriesQueued = robot !== (p.values[ROBOT_FACTORY] ?? 0) || nanite !== (p.values[NANITE_FACTORY] ?? 0);
  return buildingsFor(p.type).map((id) => {
    const meta = BUILDINGS[String(id)];
    const level = p.values[id] ?? 0;
    const queued = [...p.queue].reverse().find((q) => q.id === id);
    const next = (queued ? levelAfter(queued) : level) + 1;
    const shown = o.shown?.[id]?.next === next ? o.shown[id] : undefined;
    const cost = shown && Object.keys(pick(shown.cost)).length ? pick(shown.cost) : buildingCost(id, next, o.catchUp ?? 0);
    // the page shows the time with today's factories: it only holds while none of them is in the queue
    const time = !factoriesQueued && shown?.time != null ? shown.time : o.buildingSpeed ? buildTime(cost, robot, nanite, o.buildingSpeed) : null;
    const by = LOCKED_BY[id];
    const lock = by ? p.busy?.[by] : null;
    const busy = lock && (lock.until == null || lock.until > o.now) ? { by, until: lock.until } : null;
    const missing: Record<number, number> = {};
    let readyAt: number | null = p.time;
    let overCap = false;
    for (const res of RESOURCES) {
      const need = cost[res] ?? 0;
      if (!need) continue;
      const cap = capacityOf(p, res, o.storageFactor);
      const arrivals = (o.arrivals ?? []).map((a) => ({ at: a.at, amount: a.resources[res] ?? 0 })).filter((a) => a.amount > 0);
      const start = p.resources[res] ?? 0;
      const perHour = p.perHour[res] ?? 0;
      const have = resourceAt(start, perHour, cap, p.time, o.now, arrivals);
      // like the game's getRestPrice: cost minus the whole resources there
      if (need - Math.floor(have) > 0) missing[res] = need - Math.floor(have);
      const at = resourceReadyAt(need, start, perHour, cap, p.time, arrivals);
      if (need > cap) overCap = true;
      readyAt = at == null || readyAt == null ? null : Math.max(readyAt, at);
    }
    // buildable once the facility is free as well
    if (busy?.until != null && readyAt != null) readyAt = Math.max(readyAt, busy.until);
    const requirements = requirementsOf(id, p.values, o.research);
    const state: BuildState = requirements.some((r) => r.own < r.need)
      ? 'requirements'
      : next > meta.max
        ? 'max'
        : fieldsFull
          ? 'fields'
          : !Object.keys(missing).length
            ? busy
              ? 'busy'
              : 'buildable'
            : readyAt != null
              ? 'resources'
              : overCap
                ? 'storage'
                : 'never';
    return { id, group: buildingGroup(id), level, next, max: meta.max, requirements, cost, missing, readyAt, time, busy, state };
  });
}

/** metal, crystal and deuterium of a cost the page showed */
function pick(cost: Record<number, number>): Record<number, number> {
  const out: Record<number, number> = {};
  for (const r of RESOURCES) if (cost[r]) out[r] = cost[r];
  return out;
}
